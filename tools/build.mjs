/**
 * Produces `paper-trader.js` — one self-contained file that both serves the UI
 * and proxies market data. Run it with `node paper-trader.js`, nothing to install.
 *
 * The app's HTML/CSS/JS is inlined into a single document, then embedded as a
 * JSON string literal (JSON.stringify handles every escaping case, including
 * backticks and ${} that would break a template literal).
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { buildHTML, ROOT } from './bundle.mjs';

/**
 * Parse every inlined <script> in the built document. Bundling is string
 * surgery, and a corrupted block only shows up as a blank page in a browser —
 * this turns that into a build failure.
 */
function verifyScripts(html) {
  const blocks = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  if (blocks.length < 5) throw new Error(`only ${blocks.length} script blocks inlined — bundling looks wrong`);
  blocks.forEach((code, i) => {
    const name = (code.trim().match(/^\/\* (\S+) \*\//) || [])[1] || `block ${i}`;
    try {
      new vm.Script(code, { filename: name });
    } catch (e) {
      throw new Error(`inlined ${name} does not parse: ${e.message}`);
    }
  });
  return blocks.length;
}

/** Scope-hoist the ES modules into one file: strip local imports and `export`. */
function flatten(files) {
  const builtins = new Set();
  const bodies = [];

  for (const rel of files) {
    let src = fs.readFileSync(path.join(ROOT, rel), 'utf8');

    /*
     * Scope-hoisting flattens every module into one shared scope, so an aliased
     * import (`x as y`) would leave `y` undefined at runtime. Catch it at build
     * time rather than shipping a route that throws.
     */
    const aliased = src.match(/^import\s*\{[^}]*\bas\b[^}]*\}\s*from\s*'\.\/[^']+';$/gm);
    if (aliased) {
      throw new Error(`${rel}: aliased local import cannot be bundled — rename at the definition instead:\n  ${aliased.join('\n  ')}`);
    }

    // Collect node: builtin imports so they can be hoisted once at the top.
    src = src.replace(/^import\s+[^;]*?from\s+'node:[^']+';$/gm, (line) => {
      builtins.add(line);
      return '';
    });
    // Drop imports between our own modules — everything shares one scope now.
    src = src.replace(/^import\s+\{[\s\S]*?\}\s+from\s+'\.\/[^']+';$/gm, '');
    src = src.replace(/^import\s+[\w*\s{},]+\s+from\s+'\.\/[^']+';$/gm, '');
    // `export function x` -> `function x`, `export const x` -> `const x`.
    src = src.replace(/^export\s+(?=(async\s+)?(function|const|let|class))/gm, '');
    src = src.replace(/^export\s+\{[^}]*\};?$/gm, '');

    bodies.push(`/* ===== ${rel} ===== */\n${src.trim()}`);
  }
  return [...builtins].sort().join('\n') + '\n\n' + bodies.join('\n\n');
}

const html = buildHTML();
const scriptCount = verifyScripts(html);
const runtime = flatten(['src/http.mjs', 'src/universe.mjs', 'src/providers.mjs', 'src/server.mjs']);

const out = `#!/usr/bin/env node
/**
 * Paper Trader — a self-contained paper trading terminal.
 *
 *   node paper-trader.mjs            then open http://127.0.0.1:7777
 *   PORT=8080 node paper-trader.mjs  to use a different port
 *
 * Optional: export ANTHROPIC_API_KEY before starting to enable language-model
 * commentary in the AI companion. Without it the companion runs on computed
 * analytics, which is the default and is labelled as such in the UI.
 *
 * Paper trading only — virtual money, real prices, no brokerage, not advice.
 *
 * Generated by tools/build.mjs — edit the sources under src/, not this file.
 */

${runtime}

const APP_HTML = ${JSON.stringify(html)};

start(() => APP_HTML);
`;

fs.writeFileSync(path.join(ROOT, 'paper-trader.mjs'), out);
const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log(`built paper-trader.mjs — ${kb}kb (html ${(html.length / 1024).toFixed(1)}kb, ${scriptCount} verified script blocks)`);
